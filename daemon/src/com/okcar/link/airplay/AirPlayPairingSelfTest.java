    /** A second, deliberately separate implementation of every primitive used above. */
    private static final class Mirror {
        private static final int BLOCK = 128;
        static final byte[] PKCS8_ED = fromHex("302E020100300506032B657004220420");
        static final byte[] SPKI_ED = fromHex("302A300506032B6570032100");
        private static final byte[] PKCS8_X = fromHex("302E020100300506032B656E04220420");
        private static final byte[] SPKI_X = fromHex("302A300506032B656E032100");
        /** The X25519 base point u = 9, little-endian. */
        private static final byte[] X25519_BASE = new byte[32];
        static {
            X25519_BASE[0] = 9;
        }

        static byte[] sha512(byte[]... parts) {
            try {
                MessageDigest digest = MessageDigest.getInstance("SHA-512");
                for (byte[] part : parts) {
                    digest.update(part);
                }
                return digest.digest();
            } catch (Exception e) {
                throw new AssertionError(e);
            }
        }

        static byte[] hmacSha512(byte[] key, byte[]... parts) {
            byte[] k = key.length > BLOCK ? sha512(key) : key;
            byte[] ipad = new byte[BLOCK];
            byte[] opad = new byte[BLOCK];
            for (int i = 0; i < BLOCK; i++) {
                int b = i < k.length ? k[i] & 0xFF : 0;
                ipad[i] = (byte) (b ^ 0x36);
                opad[i] = (byte) (b ^ 0x5C);
            }
            return sha512(opad, sha512(concat(ipad, concat(parts))));
        }

        static byte[] hkdf(byte[] ikm, String salt, String info, int length) {
            byte[] prk = hmacSha512(ascii(salt), ikm);
            byte[] out = new byte[length];
            byte[] block = new byte[0];
            int pos = 0;
            int counter = 1;
            while (pos < length) {
                block = hmacSha512(prk, block, ascii(info), new byte[] {(byte) counter});
                int n = Math.min(block.length, length - pos);
                System.arraycopy(block, 0, out, pos, n);
                pos += n;
                counter++;
            }
            return out;
        }

        static byte[] tlv(int type, byte[] value) {
            if (value.length == 0) {
                return new byte[] {(byte) type, 0};
            }
            byte[] out = new byte[0];
            int off = 0;
            while (off < value.length) {
                int chunk = Math.min(255, value.length - off);
                out = concat(out, new byte[] {(byte) type, (byte) chunk},
                        Arrays.copyOfRange(value, off, off + chunk));
                off += chunk;
            }
            return out;
        }

        static byte[] tlvJoin(byte[]... parts) {
            return concat(parts);
        }

        static Map<Integer, byte[]> parseTlv(byte[] tlv) {
            Map<Integer, byte[]> out = new LinkedHashMap<Integer, byte[]>();
            int off = 0;
            while (off < tlv.length) {
                int type = tlv[off] & 0xFF;
                int len = tlv[off + 1] & 0xFF;
                byte[] value = Arrays.copyOfRange(tlv, off + 2, off + 2 + len);
                byte[] previous = out.get(type);
                out.put(type, previous == null ? value : concat(previous, value));
                off += 2 + len;
            }
            return out;
        }

        static byte[] frame(byte[] key, long counter, byte[] plaintext) throws Exception {
            byte[] header = new byte[] {(byte) (plaintext.length & 0xFF),
                    (byte) ((plaintext.length >>> 8) & 0xFF)};
            return concat(header, chachaSeal(key, nonceCounter(counter), plaintext, header));
        }

        static byte[] unframe(byte[] key, long counter, byte[] frame) throws Exception {
            int len = (frame[0] & 0xFF) | ((frame[1] & 0xFF) << 8);
            if (frame.length != 2 + len + 16) {
                throw new IllegalArgumentException("mirror: bad frame length");
            }
            byte[] header = new byte[] {frame[0], frame[1]};
            return chachaOpen(key, nonceCounter(counter), Arrays.copyOfRange(frame, 2, frame.length), header);
        }

        static byte[] chachaSeal(byte[] key, byte[] nonce, byte[] plaintext, byte[] aad) throws Exception {
            Cipher cipher = Cipher.getInstance("ChaCha20-Poly1305");
            cipher.init(Cipher.ENCRYPT_MODE, new SecretKeySpec(key, "ChaCha20"), new IvParameterSpec(nonce));
            if (aad != null && aad.length > 0) {
                cipher.updateAAD(aad);
            }
            return cipher.doFinal(plaintext);
        }

        static byte[] chachaOpen(byte[] key, byte[] nonce, byte[] sealed, byte[] aad) throws Exception {
            Cipher cipher = Cipher.getInstance("ChaCha20-Poly1305");
            cipher.init(Cipher.DECRYPT_MODE, new SecretKeySpec(key, "ChaCha20"), new IvParameterSpec(nonce));
            if (aad != null && aad.length > 0) {
                cipher.updateAAD(aad);
            }
            return cipher.doFinal(sealed);
        }

        static byte[] nonceCounter(long counter) {
            byte[] nonce = new byte[12];
            for (int i = 0; i < 8; i++) {
                nonce[4 + i] = (byte) (counter >>> (8 * i));
            }
            return nonce;
        }

        static byte[] nonceLabel(String label) {
            byte[] nonce = new byte[12];
            System.arraycopy(ascii(label), 0, nonce, 4, 8);
            return nonce;
        }

        static byte[] pad(BigInteger value) {
            byte[] raw = minimal(value);
            byte[] out = new byte[384];
            System.arraycopy(raw, 0, out, 384 - raw.length, raw.length);
            return out;
        }

        static byte[] minimal(BigInteger value) {
            if (value.signum() == 0) {
                return new byte[] {0};
            }
            byte[] raw = value.toByteArray();
            return raw.length > 1 && raw[0] == 0 ? Arrays.copyOfRange(raw, 1, raw.length) : raw;
        }

        static byte[] xor(byte[] a, byte[] b) {
            byte[] out = new byte[a.length];
            for (int i = 0; i < a.length; i++) {
                out[i] = (byte) (a[i] ^ b[i]);
            }
            return out;
        }

        static byte[] pkcs8Ed25519(byte[] seed) {
            return concat(PKCS8_ED, seed);
        }

        static PrivateKey ed25519Private(byte[] pkcs8) throws Exception {
            return KeyFactory.getInstance("Ed25519").generatePrivate(new PKCS8EncodedKeySpec(pkcs8));
        }

        static byte[] rawFromSpki(PublicKey key, byte[] prefix) {
            byte[] der = key.getEncoded();
            if (der == null || der.length != prefix.length + 32) {
                throw new AssertionError("unexpected SPKI length " + (der == null ? -1 : der.length));
            }
            return Arrays.copyOfRange(der, prefix.length, der.length);
        }

        static byte[] signEd25519(PrivateKey key, byte[] message) throws Exception {
            Signature signature = Signature.getInstance("Ed25519");
            signature.initSign(key);
            signature.update(message);
            return signature.sign();
        }

        static byte[] signEd25519(byte[] pkcs8, byte[] message) throws Exception {
            return signEd25519(ed25519Private(pkcs8), message);
        }

        static boolean verifyEd25519(byte[] rawPublic, byte[] message, byte[] signature) throws Exception {
            try {
                PublicKey key = KeyFactory.getInstance("Ed25519").generatePublic(
                        new X509EncodedKeySpec(concat(SPKI_ED, rawPublic)));
                Signature verifier = Signature.getInstance("Ed25519");
                verifier.initVerify(key);
                verifier.update(message);
                return verifier.verify(signature);
            } catch (java.security.GeneralSecurityException e) {
                // A flipped signature bit can produce an off-curve R point, which SunEC reports as
                // SignatureException("Invalid point").  That is a failed verification, not an error.
                return false;
            }
        }

        static byte[] x25519(byte[] secret, byte[] peerRaw) throws Exception {
            javax.crypto.KeyAgreement agreement = javax.crypto.KeyAgreement.getInstance("XDH");
            agreement.init(KeyFactory.getInstance("XDH")
                    .generatePrivate(new PKCS8EncodedKeySpec(concat(PKCS8_X, secret))));
            agreement.doPhase(KeyFactory.getInstance("XDH").generatePublic(
                    new X509EncodedKeySpec(concat(SPKI_X, peerRaw))), true);
            return agreement.generateSecret();
        }

        /** X25519 public key = X25519(secret, base point 9). */
        static byte[] x25519PublicRaw(byte[] secret) throws Exception {
            return x25519(secret, X25519_BASE);
        }

        static byte[] concat(byte[]... parts) {
            int total = 0;
            for (byte[] part : parts) {
                total += part.length;
            }
            byte[] out = new byte[total];
            int off = 0;
            for (byte[] part : parts) {
                System.arraycopy(part, 0, out, off, part.length);
                off += part.length;
            }
            return out;
        }

        static byte[] ascii(String s) {
            return s.getBytes(StandardCharsets.US_ASCII);
        }

        static byte[] fromHex(String hex) {
            byte[] out = new byte[hex.length() / 2];
            for (int i = 0; i < out.length; i++) {
                out[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);
            }
            return out;
        }
    }

