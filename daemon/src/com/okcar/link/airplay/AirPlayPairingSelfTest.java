    // ================================================================== 3. ChaCha + framing

    private static void testChaChaFraming() {
        final String name = "chacha20poly1305-framing";
        try {
            byte[] key = new byte[32];
            for (int i = 0; i < key.length; i++) {
                key[i] = (byte) i;
            }
            byte[] plaintext = AirPlayPairing.ascii(
                    "POST /feedback RTSP/1.0\r\nCSeq: 42\r\nUser-Agent: AirPlay/710.79.1\r\n\r\n");
            assertTrue(plaintext.length == 67, "KAT plaintext is 67 bytes");
            byte[] header = new byte[] {(byte) 0x43, 0x00};
            assertArrayEquals(AirPlayPairing.fromHex(CHACHA_KAT_SEALED),
                    AirPlayPairing.chachaSeal(key, AirPlayPairing.nonceForCounter(0), plaintext, header),
                    "ChaCha20-Poly1305 KAT with AAD = u16 LE length, counter 0");
            assertArrayEquals(AirPlayPairing.fromHex(CHACHA_KAT_SEALED_C1),
                    AirPlayPairing.chachaSeal(key, AirPlayPairing.nonceForCounter(1), plaintext, header),
                    "the same plaintext at counter 1 differs (the nonce really is the counter)");
            assertArrayEquals(AirPlayPairing.fromHex(CHACHA_KAT_PS_MSG05),
                    AirPlayPairing.chachaSeal(
                            AirPlayPairing.fromHex("202122232425262728292A2B2C2D2E2F303132333435363738393A3B3C3D3E3F"),
                            AirPlayPairing.nonceForLabel("PS-Msg05"), AirPlayPairing.fromHex("060105"), null),
                    "PS-Msg05 nonce (4 zero bytes || 8 ASCII) with no AAD");

            // The same framing through the real channel codec of a fully paired session.
            Fixture fx = new Fixture(AirPlayPairing.PAIR_SETUP_PIN);
            byte[] writeKey = fx.client.controlWriteKey();
            byte[] frame0 = fx.client.sealControl(plaintext);
            byte[] frame1 = fx.client.sealControl(plaintext);
            assertTrue((frame0[0] & 0xFF) == 67 && (frame0[1] & 0xFF) == 0,
                    "frame header u16 LE == plaintext length");
            assertTrue(frame0.length == 2 + 67 + 16, "frame length == 2 + plaintext + 16-byte tag");
            assertArrayEquals(AirPlayPairing.concat(header, AirPlayPairing.chachaSeal(
                            writeKey, AirPlayPairing.nonceForCounter(0), plaintext, header)),
                    frame0, "sealControl frame #0 uses counter 0 and AAD = the 2 length bytes");
            assertArrayEquals(AirPlayPairing.concat(header, AirPlayPairing.chachaSeal(
                            writeKey, AirPlayPairing.nonceForCounter(1), plaintext, header)),
                    frame1, "sealControl frame #1 uses counter 1 — the counter advances per message");
            assertTrue(fx.client.controlWriteCounter() == 2, "write counter advanced twice");
            assertArrayEquals(plaintext, fx.acc.controlUnseal(frame0),
                    "the accessory decrypts frame #0 with the mirrored Control-Write key");
            assertArrayEquals(plaintext, fx.client.unsealControl(fx.acc.controlSeal(plaintext)),
                    "an accessory Control-Read frame decrypts on our side");

            // Tamper detection on a frame the accessory sealed, i.e. one we would receive.
            // (A frame we sealed ourselves cannot be opened with our own read key: the two
            // directions use different keys, which is itself worth asserting.)
            expectBad("our own sealed frame must NOT open with our read key", new Action() {
                public void run() throws Exception {
                    Fixture fresh = new Fixture(AirPlayPairing.PAIR_SETUP_PIN);
                    fresh.client.unsealControl(fresh.client.sealControl(plaintext));
                }
            });
            Fixture ft = new Fixture(AirPlayPairing.PAIR_SETUP_PIN);
            final AirPlayPairing receiver = ft.client;
            final byte[] received = ft.acc.controlSeal(plaintext);
            final byte[] tampered = received.clone();
            tampered[10] ^= 0x01;
            expectBad("flipping a ciphertext byte must fail unsealing", new Action() {
                public void run() throws Exception {
                    receiver.unsealControl(tampered);
                }
            });
            final byte[] badLength = received.clone();
            badLength[0] ^= 0x01;
            expectBad("flipping the u16 length byte must fail unsealing (it is the AAD)", new Action() {
                public void run() throws Exception {
                    receiver.unsealControl(badLength);
                }
            });
            final byte[] shortFrame = Arrays.copyOf(received, received.length - 1);
            expectBad("a truncated frame must be rejected on length", new Action() {
                public void run() throws Exception {
                    receiver.unsealControl(shortFrame);
                }
            });
            expectBad("sealing more than 0x4000 bytes must be refused", new Action() {
                public void run() throws Exception {
                    receiver.sealControl(new byte[AirPlayPairing.MAX_PLAINTEXT + 1]);
                }
            });
            assertArrayEquals(plaintext, receiver.unsealControl(received),
                    "after three failed opens the read counter has not moved, so the good frame still opens");

            // 0x4000 chunking on the real iPhone's boundary, with a fresh accessory so the
            // per-direction counters stay in lockstep.
            Fixture fx3 = new Fixture(AirPlayPairing.PAIR_SETUP_PIN);
            byte[] big = new byte[AirPlayPairing.MAX_PLAINTEXT + 100];
            RANDOM.nextBytes(big);
            List<byte[]> frames = fx3.client.sealControlChunked(big);
            assertTrue(frames.size() == 2, "0x4000+100 chunks into 2 frames");
            assertTrue((frames.get(0)[0] & 0xFF) == 0x00 && (frames.get(0)[1] & 0xFF) == 0x40,
                    "the first chunk declares L = 0x4000");
            assertTrue((frames.get(1)[0] & 0xFF) == 100 && (frames.get(1)[1] & 0xFF) == 0,
                    "the second chunk declares L = 100");
            assertArrayEquals(big, AirPlayPairing.concat(fx3.acc.controlUnseal(frames.get(0)),
                    fx3.acc.controlUnseal(frames.get(1))), "the accessory reassembles the chunked message");
            pass(name, "KAT (independent impl) + framing + counter + tamper + 0x4000 chunking");
        } catch (Throwable t) {
            fail(name, t);
        }
    }

