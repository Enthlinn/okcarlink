    /**
     * Parses the real pair-setup bodies captured from our own pcaps, re-encodes them and checks
     * every a-independent SRP derivation.  It does NOT (and cannot) recompute the captured M1:
     * A = g^a mod N and `a` is not on the wire — see the file header.
     */
    private static void testCapturedSrpBodies() {
        final String name = "srp-captured-bodies (wp2 + wp3 pcaps)";
        try {
            String[] labels = {"the recorded capture", "the recorded capture"};
            byte[][] m2b = {AirPlayPairing.fromHex(CAP_WP2_0_M2_BODY), AirPlayPairing.fromHex(CAP_WP3_1_M2_BODY)};
            byte[][] m3b = {AirPlayPairing.fromHex(CAP_WP2_0_M3_BODY), AirPlayPairing.fromHex(CAP_WP3_1_M3_BODY)};
            byte[][] m4b = {AirPlayPairing.fromHex(CAP_WP2_0_M4_BODY), AirPlayPairing.fromHex(CAP_WP3_1_M4_BODY)};

            StringBuilder detail = new StringBuilder();
            for (int i = 0; i < m2b.length; i++) {
                assertTrue(m2b[i].length == 409, labels[i] + " M2 is 409 bytes");
                assertTrue(m3b[i].length == 457, labels[i] + " M3 is 457 bytes");
                assertTrue(m4b[i].length == 69, labels[i] + " M4 is 69 bytes");

                Map<Integer, byte[]> m2 = AirPlayPairing.parseTlv(m2b[i]);
                Map<Integer, byte[]> m3 = AirPlayPairing.parseTlv(m3b[i]);
                Map<Integer, byte[]> m4 = AirPlayPairing.parseTlv(m4b[i]);
                assertTrue(m2.get(AirPlayPairing.TLV_STATE)[0] == 2, "M2 State=2");
                assertTrue(m2.get(AirPlayPairing.TLV_SALT).length == 16, "M2 Salt is 16 bytes");
                assertTrue(m2.get(AirPlayPairing.TLV_PUBLIC_KEY).length == 384, "M2 PublicKey(B) is 384 bytes");
                assertTrue(m3.get(AirPlayPairing.TLV_STATE)[0] == 3, "M3 State=3");
                assertTrue(m3.get(AirPlayPairing.TLV_PUBLIC_KEY).length == 384,
                        "M3 PublicKey(A) merges the 255+129 fragments back to 384 bytes");
                assertTrue(m3.get(AirPlayPairing.TLV_PROOF).length == 64, "M3 Proof(M1) is 64 bytes");
                assertTrue(m4.get(AirPlayPairing.TLV_STATE)[0] == 4, "M4 State=4");
                assertTrue(m4.get(AirPlayPairing.TLV_PROOF).length == 64, "M4 Proof(M2) is 64 bytes");

                // Re-encode strictly in the order the fragments appear on the wire.  This is
                // deliberately order-agnostic: the two accessories disagree (wp2 M2 is
                // State,Salt,PublicKey; wp3 M2 is State,PublicKey,Salt), which is exactly why
                // both this parser and the accessory parsers must be keyed by TLV type.
                assertArrayEquals(m2b[i], reencodeInWireOrder(m2b[i]),
                        labels[i] + " M2 re-encodes byte-for-byte in the capture's own TLV order");
                assertArrayEquals(m3b[i], reencodeInWireOrder(m3b[i]),
                        labels[i] + " M3 re-encodes byte-for-byte in the capture's own TLV order");
                assertArrayEquals(m4b[i], reencodeInWireOrder(m4b[i]),
                        labels[i] + " M4 re-encodes byte-for-byte in the capture's own TLV order");

                byte[] salt = m2.get(AirPlayPairing.TLV_SALT);
                BigInteger b = new BigInteger(1, m2.get(AirPlayPairing.TLV_PUBLIC_KEY));
                BigInteger a = new BigInteger(1, m3.get(AirPlayPairing.TLV_PUBLIC_KEY));
                BigInteger n = AirPlayPairing.SRP_N;
                assertTrue(a.signum() > 0 && a.compareTo(n) < 0, "captured A is in [1, N)");
                assertTrue(b.signum() > 0 && b.compareTo(n) < 0, "captured B is in [1, N)");

                byte[] x = AirPlayPairing.srpComputeX(salt, "Pair-Setup", "3939");
                assertArrayEquals(Mirror.sha512(salt, Mirror.sha512(AirPlayPairing.ascii("Pair-Setup:3939"))),
                        x, "x = H(salt || H(I || ':' || P)) matches an independent computation");
                assertTrue(x.length == 64, "x is 64 bytes");
                BigInteger k = new BigInteger(1, AirPlayPairing.sha512(AirPlayPairing.pad(n),
                        AirPlayPairing.pad(AirPlayPairing.SRP_G)));
                BigInteger u = new BigInteger(1,
                        AirPlayPairing.sha512(AirPlayPairing.pad(a), AirPlayPairing.pad(b)));
                assertTrue(u.signum() != 0, "u != 0");
                BigInteger v = AirPlayPairing.SRP_G.modPow(new BigInteger(1, x), n);
                BigInteger residual = b.subtract(k.multiply(v)).mod(n);
                assertTrue(residual.signum() != 0, "B - k*g^x != 0, so B is a legal g^b + k*v");
                assertTrue(residual.gcd(n).equals(BigInteger.ONE), "B - k*g^x is invertible mod N");
                detail.append(labels[i]).append(" salt=")
                        .append(AirPlayPairing.toHex(salt).substring(0, 8)).append(".. ");
            }
            System.out.println("NOTE " + name + ": wp2's M2 is State,Salt,PublicKey but wp3's M2 is"
                    + " State,PublicKey,Salt — the two accessories order their TLVs differently, so"
                    + " both sides must parse by type (ours does; our own M1/M3/M5 emission follows"
                    + " the real iPhone's order).");
            System.out.println("NOTE " + name + ": the captured M1 proofs are NOT reproducible from"
                    + " (salt, B) — the client exponent `a` (A = g^a mod N) is never on the wire and"
                    + " neither accessory logged its own b.  Pinned here: wire format, group and"
                    + " x/k/u/v; the formulas themselves are pinned by srp-kat-fixed-inputs and the"
                    + " end-to-end test.");
            pass(name, detail + "values parsed, re-encoded byte-for-byte, x/k/u/v verified");
        } catch (Throwable t) {
            fail(name, t);
        }
    }

    /**
     * Re-encodes a captured TLV body using AirPlayPairing.tlv() in the order its fragments appear,
     * merging consecutive same-type runs (and skipping 0xFF,0x00 separators).  Applying this to a
     * captured body and getting the identical bytes back exercises our encoder against real wire
     * bytes without assuming any particular TLV order.
     */
    private static byte[] reencodeInWireOrder(byte[] body) {
        java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream();
        int off = 0;
        while (off < body.length) {
            if (off + 2 > body.length) {
                throw new AssertionError("truncated captured body at " + off);
            }
            int type = body[off] & 0xFF;
            int len = body[off + 1] & 0xFF;
            byte[] value = Arrays.copyOfRange(body, off + 2, off + 2 + len);
            off += 2 + len;
            while (off + 2 <= body.length) {
                int nextType = body[off] & 0xFF;
                int nextLen = body[off + 1] & 0xFF;
                if (nextType == AirPlayPairing.TLV_SEPARATOR && nextLen == 0) {
                    off += 2;
                    continue;
                }
                if (nextType != type) {
                    break;
                }
                value = AirPlayPairing.concat(value, Arrays.copyOfRange(body, off + 2, off + 2 + nextLen));
                off += 2 + nextLen;
            }
            byte[] encoded = AirPlayPairing.tlv(type, value);
            out.write(encoded, 0, encoded.length);
        }
        return out.toByteArray();
    }

    /**
     * Fixed-input SRP KAT.  Expected values were produced by an independent Python
     * implementation of the xcertplay accessory formula with
     *   salt = 00112233445566778899aabbccddeeff, a = 0x01..0x20,
     *   b = 0x2122..3c || 0x00000160
     * chosen so that S has a leading zero byte: this pins K = H(minimal(S)), not H(PAD(S)).
     */
    private static void testSrpFixedInputKat() {
        final String name = "srp-kat-fixed-inputs";
        try {
            byte[] salt = AirPlayPairing.fromHex("00112233445566778899AABBCCDDEEFF");
            BigInteger a = new BigInteger(1,
                    Mirror.fromHex("0102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1F20"));
            BigInteger b = new BigInteger(1, AirPlayPairing.fromHex(KAT_B_SECRET));
            BigInteger n = AirPlayPairing.SRP_N;
            BigInteger g = AirPlayPairing.SRP_G;

            BigInteger k = new BigInteger(1, Mirror.sha512(Mirror.pad(n), Mirror.pad(g)));
            BigInteger x = new BigInteger(1, Mirror.sha512(salt, Mirror.sha512(
                    AirPlayPairing.ascii("Pair-Setup"), AirPlayPairing.ascii(":"),
                    AirPlayPairing.ascii("3939"))));
            BigInteger v = g.modPow(x, n);
            BigInteger aPub = g.modPow(a, n);
            BigInteger bPub = k.multiply(v).add(g.modPow(b, n)).mod(n);
            BigInteger u = new BigInteger(1, Mirror.sha512(Mirror.pad(aPub), Mirror.pad(bPub)));
            BigInteger sClient = bPub.subtract(k.multiply(v)).mod(n).modPow(a.add(u.multiply(x)), n);
            BigInteger sServer = aPub.multiply(v.modPow(u, n)).mod(n).modPow(b, n);
            assertTrue(sClient.equals(sServer), "client and server premaster secrets agree");
            assertTrue(Mirror.minimal(sClient).length == 383,
                    "this KAT's S has a leading zero byte, so minimal(S) != pad(S)");
            byte[] kWire = Mirror.sha512(Mirror.minimal(sClient));
            assertArrayEquals(AirPlayPairing.fromHex(KAT_EXPECTED_K), kWire,
                    "K = H(minimal(S)) — the xcertplay/airplay2-receiver/srptools convention");
            assertTrue(!Arrays.equals(kWire, Mirror.sha512(Mirror.pad(sClient))),
                    "K != H(pad(S)) for this KAT, so the KAT really discriminates");

            byte[] xor = Mirror.xor(Mirror.sha512(Mirror.minimal(n)), Mirror.sha512(Mirror.minimal(g)));
            byte[] m1 = Mirror.sha512(xor, Mirror.sha512(AirPlayPairing.ascii("Pair-Setup")), salt,
                    Mirror.pad(aPub), Mirror.pad(bPub), kWire);
            byte[] m2 = Mirror.sha512(Mirror.pad(aPub), m1, kWire);
            assertArrayEquals(AirPlayPairing.fromHex(KAT_EXPECTED_A), AirPlayPairing.pad(aPub), "KAT A");
            assertArrayEquals(AirPlayPairing.fromHex(KAT_EXPECTED_B), AirPlayPairing.pad(bPub), "KAT B");
            assertArrayEquals(AirPlayPairing.fromHex(KAT_EXPECTED_U),
                    Mirror.sha512(Mirror.pad(aPub), Mirror.pad(bPub)), "KAT u");
            assertArrayEquals(AirPlayPairing.fromHex(KAT_EXPECTED_M1), m1, "KAT M1");
            assertArrayEquals(AirPlayPairing.fromHex(KAT_EXPECTED_M2), m2, "KAT M2");
            assertArrayEquals(Mirror.sha512(salt, Mirror.sha512(AirPlayPairing.ascii("Pair-Setup:3939"))),
                    AirPlayPairing.srpComputeX(salt, "Pair-Setup", "3939"), "production x matches the KAT");

            byte[] xorPaddedG = Mirror.xor(Mirror.sha512(Mirror.minimal(n)), Mirror.sha512(Mirror.pad(g)));
            assertTrue(!Arrays.equals(xor, xorPaddedG),
                    "M1 hashes minimal(g) (0x05), not pad(g) — the two differ, and xcertplay uses 0x05");
            pass(name, "Python-generated KAT matches, including the minimal-S discriminator");
        } catch (Throwable t) {
            fail(name, t);
        }
    }

