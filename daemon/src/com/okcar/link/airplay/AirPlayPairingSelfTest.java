    /**
     * An independent accessory: its own SRP server, its own Ed25519/X25519 handling and its own
     * channel codec.  It knows the PIN and therefore its own `b`, which is what lets it verify a
     * real M1 from the production client even though no captured M1 can be verified.
     */
    private static final class FakeAccessory {
        final byte[] id;
        final byte[] ltPub;
        private final String mPin;
        private final PrivateKey mLtPriv;
        private byte[] mClientLtpk;

        private byte[] mSalt;
        private BigInteger mVerifier;
        private BigInteger mB;
        private BigInteger mBSecret;
        private byte[] mSessionKey;
        boolean clientProofOk;
        boolean clientSigOk;
        boolean clientVerifySigOk;

        private byte[] mEphSecret;
        private byte[] mEphPub;
        private byte[] mClientEphPub;
        private byte[] mShared;
        byte[] controlRead;
        byte[] controlWrite;
        byte[] eventRead;
        byte[] eventWrite;
        private long mCtrlReadCtr;
        private long mCtrlWriteCtr;
        private long mEvtReadCtr;
        private long mEvtWriteCtr;

        FakeAccessory(String pin) throws Exception {
            mPin = pin;
            id = AirPlayPairing.ascii("A1B2C3D4-E5F6-7788-99AA-BBCCDDEEFF00");
            KeyPair pair = KeyPairGenerator.getInstance("Ed25519").generateKeyPair();
            mLtPriv = pair.getPrivate();
            ltPub = Mirror.rawFromSpki(pair.getPublic(), Mirror.SPKI_ED);
        }

        byte[] m2() throws Exception {
            mSalt = new byte[16];
            RANDOM.nextBytes(mSalt);
            BigInteger x = new BigInteger(1, Mirror.sha512(mSalt,
                    Mirror.sha512(AirPlayPairing.ascii("Pair-Setup:" + mPin))));
            mVerifier = AirPlayPairing.SRP_G.modPow(x, AirPlayPairing.SRP_N);
            byte[] secret = new byte[32];
            RANDOM.nextBytes(secret);
            mBSecret = new BigInteger(1, secret);
            BigInteger k = new BigInteger(1, Mirror.sha512(Mirror.pad(AirPlayPairing.SRP_N),
                    Mirror.pad(AirPlayPairing.SRP_G)));
            mB = k.multiply(mVerifier)
                    .add(AirPlayPairing.SRP_G.modPow(mBSecret, AirPlayPairing.SRP_N))
                    .mod(AirPlayPairing.SRP_N);
            return Mirror.tlvJoin(Mirror.tlv(6, new byte[] {2}), Mirror.tlv(2, mSalt),
                    Mirror.tlv(3, Mirror.pad(mB)));
        }

        byte[] m4(byte[] m3) throws Exception {
            Map<Integer, byte[]> tlv = Mirror.parseTlv(m3);
            byte[] aRaw = tlv.get(3);
            byte[] clientM1 = tlv.get(4);
            BigInteger a = new BigInteger(1, aRaw);
            BigInteger u = new BigInteger(1, Mirror.sha512(Mirror.pad(a), Mirror.pad(mB)));
            BigInteger s = a.multiply(mVerifier.modPow(u, AirPlayPairing.SRP_N))
                    .mod(AirPlayPairing.SRP_N).modPow(mBSecret, AirPlayPairing.SRP_N);
            mSessionKey = Mirror.sha512(Mirror.minimal(s));
            byte[] xor = Mirror.xor(Mirror.sha512(Mirror.minimal(AirPlayPairing.SRP_N)),
                    Mirror.sha512(Mirror.minimal(AirPlayPairing.SRP_G)));
            byte[] expected = Mirror.sha512(xor, Mirror.sha512(AirPlayPairing.ascii("Pair-Setup")),
                    mSalt, Mirror.pad(a), Mirror.pad(mB), mSessionKey);
            clientProofOk = Arrays.equals(expected, clientM1);
            // Even when the client's proof is wrong we return our own M2, so it is the client's
            // verification path that rejects it (a real accessory could answer Error=2 instead).
            return Mirror.tlvJoin(Mirror.tlv(6, new byte[] {4}),
                    Mirror.tlv(4, Mirror.sha512(Mirror.pad(a), clientM1, mSessionKey)));
        }

        byte[] m6(byte[] m5) throws Exception {
            Map<Integer, byte[]> tlv = Mirror.parseTlv(m5);
            byte[] kEnc = Mirror.hkdf(mSessionKey, "Pair-Setup-Encrypt-Salt", "Pair-Setup-Encrypt-Info", 32);
            byte[] inner = Mirror.chachaOpen(kEnc, Mirror.nonceLabel("PS-Msg05"), tlv.get(5), null);
            Map<Integer, byte[]> sub = Mirror.parseTlv(inner);
            byte[] clientId = sub.get(1);
            mClientLtpk = sub.get(3);
            byte[] deviceX = Mirror.hkdf(mSessionKey, "Pair-Setup-Controller-Sign-Salt",
                    "Pair-Setup-Controller-Sign-Info", 32);
            clientSigOk = Mirror.verifyEd25519(mClientLtpk,
                    Mirror.concat(deviceX, clientId, mClientLtpk), sub.get(10));
            byte[] accX = Mirror.hkdf(mSessionKey, "Pair-Setup-Accessory-Sign-Salt",
                    "Pair-Setup-Accessory-Sign-Info", 32);
            byte[] accSig = Mirror.signEd25519(mLtPriv, Mirror.concat(accX, id, ltPub));
            byte[] out = Mirror.tlvJoin(Mirror.tlv(1, id), Mirror.tlv(3, ltPub), Mirror.tlv(10, accSig));
            byte[] sealed = Mirror.chachaSeal(kEnc, Mirror.nonceLabel("PS-Msg06"), out, null);
            return Mirror.tlvJoin(Mirror.tlv(6, new byte[] {6}), Mirror.tlv(5, sealed));
        }

        byte[] pvM2(byte[] m1) throws Exception {
            mClientEphPub = Mirror.parseTlv(m1).get(3);
            mEphSecret = new byte[32];
            RANDOM.nextBytes(mEphSecret);
            mEphPub = Mirror.x25519PublicRaw(mEphSecret);
            mShared = Mirror.x25519(mEphSecret, mClientEphPub);
            byte[] kv = Mirror.hkdf(mShared, "Pair-Verify-Encrypt-Salt", "Pair-Verify-Encrypt-Info", 32);
            byte[] sig = Mirror.signEd25519(mLtPriv, Mirror.concat(mEphPub, id, mClientEphPub));
            byte[] inner = Mirror.tlvJoin(Mirror.tlv(1, id), Mirror.tlv(10, sig));
            byte[] sealed = Mirror.chachaSeal(kv, Mirror.nonceLabel("PV-Msg02"), inner, null);
            return Mirror.tlvJoin(Mirror.tlv(6, new byte[] {2}), Mirror.tlv(3, mEphPub), Mirror.tlv(5, sealed));
        }

        byte[] pvM4(byte[] m3) throws Exception {
            Map<Integer, byte[]> tlv = Mirror.parseTlv(m3);
            byte[] kv = Mirror.hkdf(mShared, "Pair-Verify-Encrypt-Salt", "Pair-Verify-Encrypt-Info", 32);
            byte[] inner = Mirror.chachaOpen(kv, Mirror.nonceLabel("PV-Msg03"), tlv.get(5), null);
            Map<Integer, byte[]> sub = Mirror.parseTlv(inner);
            clientVerifySigOk = Mirror.verifyEd25519(mClientLtpk,
                    Mirror.concat(mClientEphPub, sub.get(1), mEphPub), sub.get(10));
            // The accessory reads what we write with Control-Write, and writes with Control-Read.
            controlRead = Mirror.hkdf(mShared, "Control-Salt", "Control-Write-Encryption-Key", 32);
            controlWrite = Mirror.hkdf(mShared, "Control-Salt", "Control-Read-Encryption-Key", 32);
            eventRead = Mirror.hkdf(mShared, "Events-Salt", "Events-Read-Encryption-Key", 32);
            eventWrite = Mirror.hkdf(mShared, "Events-Salt", "Events-Write-Encryption-Key", 32);
            return Mirror.tlvJoin(Mirror.tlv(6, new byte[] {4}));
        }

        byte[] controlSeal(byte[] plaintext) throws Exception {
            return Mirror.frame(controlWrite, mCtrlWriteCtr++, plaintext);
        }

        byte[] controlUnseal(byte[] frame) throws Exception {
            byte[] out = Mirror.unframe(controlRead, mCtrlReadCtr, frame);
            mCtrlReadCtr++;
            return out;
        }

        byte[] eventSeal(byte[] plaintext) throws Exception {
            return Mirror.frame(eventWrite, mEvtWriteCtr++, plaintext);
        }

        byte[] eventUnseal(byte[] frame) throws Exception {
            byte[] out = Mirror.unframe(eventRead, mEvtReadCtr, frame);
            mEvtReadCtr++;
            return out;
        }
    }

