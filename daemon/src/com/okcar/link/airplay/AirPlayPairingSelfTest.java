    // ================================================================== 1. TLV8

    private static void testTlv8() {
        final String name = "tlv8-round-trip";
        try {
            byte[] big = new byte[300];
            for (int i = 0; i < big.length; i++) {
                big[i] = (byte) i;
            }
            byte[] encoded = AirPlayPairing.tlv(0x03, big);
            assertTrue(encoded.length == 2 + 255 + 2 + 45, "300-byte value must fragment as 2+255+2+45");
            assertTrue((encoded[0] & 0xFF) == 0x03 && (encoded[1] & 0xFF) == 255, "first fragment header");
            assertTrue((encoded[257] & 0xFF) == 0x03 && (encoded[258] & 0xFF) == 45, "second fragment header");
            Map<Integer, byte[]> parsed = AirPlayPairing.parseTlv(encoded);
            assertTrue(parsed.size() == 1, "one merged entry");
            assertArrayEquals(big, parsed.get(0x03), "fragmented value merges back");

            byte[] empty = AirPlayPairing.tlv(0x0A, new byte[0]);
            assertArrayEquals(new byte[] {0x0A, 0x00}, empty, "empty value encodes as type,0x00");
            Map<Integer, byte[]> emptyParsed = AirPlayPairing.parseTlv(empty);
            assertTrue(emptyParsed.containsKey(0x0A), "empty value present after parse");
            assertTrue(emptyParsed.get(0x0A).length == 0, "empty value stays empty");

            byte[] exactly255 = AirPlayPairing.tlv(0x01, new byte[255]);
            assertTrue(exactly255.length == 257, "255-byte value is one fragment, no trailing 0-length item");

            byte[] separated = AirPlayPairing.concat(encoded, new byte[] {(byte) 0xFF, 0x00},
                    AirPlayPairing.tlv(0x04, new byte[] {9}));
            Map<Integer, byte[]> sepParsed = AirPlayPairing.parseTlv(separated);
            assertArrayEquals(big, sepParsed.get(0x03), "0xFF separator does not break the merge");
            assertTrue(sepParsed.get(0x04)[0] == 9, "separate type still decoded");
            List<Integer> order = new ArrayList<Integer>(sepParsed.keySet());
            assertTrue(order.get(0) == 0x03 && order.get(1) == 0x04, "parse keeps first-appearance order");

            expectBad("truncated TLV must be rejected", new Action() {
                public void run() throws Exception {
                    AirPlayPairing.parseTlv(new byte[] {0x03, 0x10, 1, 2, 3});
                }
            });
            expectBad("a length that overruns the buffer must be rejected", new Action() {
                public void run() throws Exception {
                    AirPlayPairing.parseTlv(new byte[] {0x03, (byte) 0xFF, 1, 2});
                }
            });
            pass(name, "fragmentation, empty value, 255-byte value, separator, merge, truncation");
        } catch (Throwable t) {
            fail(name, t);
        }
    }

