/*
 * AirPlayPairingSelfTest — host-JVM verification for AirPlayPairing.
 *
 *   javac -d .car-test/pairing-out \
 *       okcar-1.0/okcar/apps/OkCarLink/src/com/okcar/link/airplay/AirPlayPairing.java \
 *       okcar-1.0/okcar/apps/OkCarLink/src/com/okcar/link/airplay/AirPlayPairingSelfTest.java
 *   java -cp .car-test/pairing-out com.okcar.link.airplay.AirPlayPairingSelfTest
 *
 * Prints one PASS/FAIL line per test and exits non-zero if anything failed.
 *
 * What is checked, and where the *expected* values come from (nothing here is invented):
 *
 *   1. TLV8 round trip: >255-byte fragmentation, an empty value, a 255-byte value, a 0xFF
 *      separator between fragments, merge-on-parse, and rejection of truncated input.
 *   2. HKDF-SHA-512 against values generated with an independent implementation:
 *          openssl kdf -keylen 42 -kdfopt digest:SHA512 -kdfopt hexkey:0b0b..(22B) \
 *              -kdfopt hexsalt:000102030405060708090a0b0c -kdfopt hexinfo:f0f1..f9 HKDF
 *      (OpenSSL 3.5.5), plus two protocol-shaped vectors with salt "Control-Salt" /
 *      info "Control-Write-Encryption-Key" and salt "Events-Salt" / info
 *      "Events-Read-Encryption-Key".  The exact invocations are repeated next to the constants.
 *   3. ChaCha20-Poly1305 framing: a KAT generated with Python `cryptography` 46.0.5
 *      (OpenSSL-backed, therefore independent of javax.crypto) for key 00..1f, AAD = u16 LE
 *      plaintext length and nonce = 4 zero bytes || u64 LE counter; then that AirPlayPairing's
 *      sealControl output equals header || chachaSeal(key, counter) for counters 0 and 1; plus
 *      tamper detection (ciphertext flip, length-byte flip, truncation) and 0x4000 chunking.
 *   4. Providers: published RFC 7748 §6.1 X25519 and RFC 8032 §7.1 Ed25519 vectors, which also
 *      prove that the hand-built RFC 8410 DER wrappers produce the right keys.
 *   5. SRP-6a: (a) real captured pair-setup bodies from our own pcaps are parsed and
 *      re-encoded byte-for-byte and their deterministic derivations (k, x, u, v) are checked;
 *      (b) a fixed-input client/server KAT whose expected values were generated by an
 *      independent Python implementation of the xcertplay accessory formula, with S chosen to
 *      have a leading zero byte so that K = H(minimal(S)) is pinned rather than H(PAD(S));
 *      (c) the production client against an in-test SRP server, mutual proofs, wrong PIN.
 *   6. End-to-end pair-setup + pair-verify against an in-test accessory, key equality in both
 *      directions (including the inverted event-channel labels) and the sealed-channel codec.
 *   7. The DataStream key of the step-⑤ iAP2 tunnel: HKDF-SHA-512 over the pair-verify shared
 *      secret with salt "DataStream-Salt" + the **unsigned** ASCII decimal of the seed, checked
 *      against the FakeAccessory's own shared secret and an independent HKDF.  The captured
 *      iPhone sent a negative seed (-2506203275301336508) whose key the receiver derived from
 *      the unsigned rendering, so a negative seed is part of the vector set.
 *
 * Honest limitation, checked and reported rather than hidden: the captured M1 proofs CANNOT be
 * recomputed.  A = g^a mod N and the client's secret exponent `a` never appears on the wire
 * (the session-analysis notes §6.1: "the PIN itself is never transmitted"), nor did either
 * accessory log its own `b`.  Test 5(a) therefore pins the wire format, the group and the
 * a-independent derivations, while 5(b)/(c) pin the formulas themselves.
 *
 * The in-test Mirror/FakeAccessory code below is a deliberately separate implementation
 * (manual HMAC, its own TLV codec, its own DER key construction) so that agreement with
 * AirPlayPairing is meaningful, and the expected constants all come from outside Java.
 */

